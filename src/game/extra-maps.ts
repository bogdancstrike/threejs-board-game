import type { MapTheme } from "./maps";
import type { Mystery } from "./data";
type Family = MapTheme["theme"];
function shift(hex: string, amount: number) {
  const n = parseInt(hex.slice(1), 16);
  return (
    "#" +
    [n >> 16, (n >> 8) & 255, n & 255]
      .map((v) =>
        Math.max(0, Math.min(255, v + amount))
          .toString(16)
          .padStart(2, "0"),
      )
      .join("")
  );
}
function make(
  id: string,
  name: string,
  tagline: string,
  description: string,
  theme: Family,
  color: string,
  water: string,
  sky: string,
  foliage: string,
  accent: string,
  regions: string[],
  story: [string, string, string, string],
): MapTheme {
  const choice = (
    title: string,
    text: string,
    a: string,
    b: string,
  ): Mystery => ({
    title,
    text,
    icon:
      theme === "ocean"
        ? "waves"
        : theme === "ice"
          ? "snowflake"
          : theme === "volcano"
            ? "flame"
            : "sparkles",
    choices: [
      {
        label: a,
        detail: "Press onward · move 2 tiles and discover a clue",
        gold: 0,
        clues: 1,
        move: 2,
      },
      {
        label: b,
        detail: "Explore the secret · gain 3 gold and a clue",
        gold: 3,
        clues: 1,
        move: 0,
      },
    ],
  });
  return {
    id,
    name,
    tagline,
    description,
    theme,
    icon: {
      forest: "trees",
      dragon: "flame",
      ice: "snowflake",
      desert: "sun",
      sakura: "flower-2",
      volcano: "mountain",
      ocean: "waves",
      mushroom: "sprout",
      astral: "orbit",
      clockwork: "settings-2",
    }[theme],
    terrain: [shift(color, -10), color, shift(color, 10), shift(color, 23)],
    rock: shift(color, -48),
    water,
    sky,
    foliage,
    accent,
    roof: shift(accent, -50),
    regions,
    encounters: [
      choice(...story),
      choice(
        `A message from ${regions[3]}`,
        `A sealed note bears the mark of ${regions[3]}. “The old way through ${regions[2]} still remembers those who travel with courage.” The seal begins to glow.`,
        "Follow the glowing seal",
        "Study the forgotten route",
      ),
    ],
  };
}
